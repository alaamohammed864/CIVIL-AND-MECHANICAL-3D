export const CURRENCY_CONFIG: Record<CurrencyCode, { symbol: string; rateFromUSD: number; decimals: number }> = {
  USD: { symbol: '$', rateFromUSD: 1, decimals: 2 },
  EUR: { symbol: '€', rateFromUSD: 0.92, decimals: 2 },
  IQD: { symbol: 'IQD ', rateFromUSD: 1310, decimals: 0 },
};

export function formatCurrency(amountUSD: number, currency: CurrencyCode): string {
  const cfg = CURRENCY_CONFIG[currency];
  const converted = amountUSD * cfg.rateFromUSD;
  return `${cfg.symbol}${converted.toLocaleString('en-US', {
    minimumFractionDigits: cfg.decimals,
    maximumFractionDigits: cfg.decimals,
  })}`;
}
